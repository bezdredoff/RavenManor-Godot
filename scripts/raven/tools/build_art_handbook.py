"""Validate the frozen art evidence and build a read-only/offline-friendly book.
This never accesses ComfyUI, models, the user's local VNCCS library or a GPU.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import zipfile

ROOT=Path(__file__).resolve().parents[3]
WEB=ROOT/'art-handbook'
SOURCE=ROOT/'data/raven/production/art_workflow_handbook.json'
RASTER={'.png','.webp','.jpg','.jpeg'}
def read(p):return json.loads(Path(p).read_text(encoding='utf-8'))
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def confined(root,path):
    p=(root/path).resolve()
    if not p.is_relative_to(root.resolve()):raise ValueError('Path escapes its root: '+path)
    return p

def validate(data, root=ROOT, web=WEB):
    ids=[a['id'] for a in data['assets']];recipes={r['id']:r for r in data['recipes']}
    assert len(ids)==len(set(ids)), 'Duplicate image ID'
    assert len(recipes)==len(data['recipes']), 'Duplicate recipe ID'
    represented={a['image'] for a in data['assets'] if a.get('image')}
    reused=data.get('reusedAssets', [])
    reused_paths={a['image'] for a in reused}
    assert len(reused_paths)==len(reused), 'Duplicate reused image path'
    assert not (represented & reused_paths), 'Image cannot be both generated and reused'
    for asset in reused:
        image=confined(root,asset['image'])
        assert image.is_file() and sha(image)==asset['sha256'], asset['id']+' reused source SHA mismatch'
        assert asset['sourceCommit'] and asset['sourcePath'], asset['id']+' lacks source provenance'
    represented |= reused_paths
    existing={p.relative_to(root).as_posix() for p in (root/'assets').rglob('*') if p.suffix.lower() in RASTER}
    assert represented==existing, 'Repository raster coverage mismatch: '+str(sorted(existing^represented))
    active={e['id'] for name in ['vn_character_catalog','vn_background_catalog'] for e in read(root/'data/raven/production'/(name+'.json'))['entries']}
    assert active<=set(ids), 'Missing published VN art'
    for a in data['assets']:
        assert a['recipeId'] in recipes, a['id']
        assert a['id'] in recipes[a['recipeId']]['outputs'], a['id']+' lacks recipe binding'
        if a.get('image'):
            image=confined(root,a['image']);assert image.is_file() and sha(image)==a['sha256'], a['id']+' source SHA mismatch'
        if a.get('preview'):assert confined(web,a['preview']).is_file(), a['id']+' missing preview'
        for rid in a.get('chain',[]):assert rid in recipes
    for r in data['recipes']:
        assert set(r['outputs'])<=set(ids), r['id']+' unknown output'
        for artifact in r['artifacts']:
            if artifact.get('path'):
                p=confined(web,artifact['path']);assert p.is_file(), str(p)
                assert sha(p)==artifact['sha256'], r['id']+' artifact SHA mismatch: '+artifact['path']
            if artifact.get('repoPath'):assert confined(root,artifact['repoPath']).is_file()
        for inp in r['inputs']:
            p=confined(web,inp['path']);assert p.is_file() and sha(p)==inp['sha256'], r['id']+' input SHA mismatch'
            assert inp['installName'].startswith('RavenHandbook/') and '..' not in inp['installName']
    # Unknown ChatGPT sampling parameters must stay unknown.
    for r in data['recipes']:
        if r['stage']=='background':assert r['parameters']['seed'] is None and r['parameters']['model'] is None
    return True

def payload():
    data=read(SOURCE);validate(data)
    content=read(WEB/'content.json');environment=read(WEB/data['environment'])
    return {'catalog':data,'content':content,'environment':environment}

def generated(p):
    merged={**p['catalog'],'environmentSnapshot':p['environment'],'readingGuide':'files/AGENT_GUIDE.md','journey':p['content']['journey']}
    json_text=json.dumps(merged,ensure_ascii=False,indent=2)+'\n'
    js_text='/* Generated by build_art_handbook.py; edit the tracked sources. */\nwindow.RAVEN_HANDBOOK = '+json.dumps(p,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')+';\n'
    return {'catalog.json':json_text,'data.js':js_text}

def make_download(web):
    target=web/'downloads/workflow-pack.zip';target.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(target,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as archive:
        for name in ['index.html','style.css','app.js','data.js','catalog.json','content.json']:
            archive.write(web/name,name)
        for folder in ['files','media']:
            for p in sorted((web/folder).rglob('*')):
                if p.is_file() and '__pycache__' not in p.parts:archive.write(p,p.relative_to(web).as_posix())
    return target

def bundle(p,target):
    target=Path(target);target.mkdir(parents=True,exist_ok=True)
    shutil.copytree(WEB,target,dirs_exist_ok=True,ignore=shutil.ignore_patterns('downloads','tests','__pycache__','.gdignore'))
    # Godot's PCK does not expose original images to an HTML page. Copy only
    # referenced repository rasters next to the book, without duplicating Git blobs.
    for a in p['catalog']['assets']:
        if a.get('image'):
            dest=confined(target.parent,a['image']);dest.parent.mkdir(parents=True,exist_ok=True)
            shutil.copy2(ROOT/a['image'],dest)
    make_download(target)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--write',action='store_true')
    parser.add_argument('--make-download',action='store_true')
    parser.add_argument('--bundle-to',type=Path)
    args=parser.parse_args();p=payload()
    for name,text in generated(p).items():
        file=WEB/name
        if args.write:file.write_text(text,encoding='utf-8',newline='\n')
        else:assert file.is_file() and file.read_text(encoding='utf-8')==text, name+' is stale; use --write'
    if args.make_download:make_download(WEB)
    if args.bundle_to:bundle(p,args.bundle_to)
    print(f"Raven art handbook PASS: {len(p['catalog']['assets'])} images, {len(p['catalog']['recipes'])} recipes; all repository rasters and artifact hashes covered")

if __name__=='__main__':main()
